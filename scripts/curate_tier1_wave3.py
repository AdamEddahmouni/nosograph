def update_disease(disease_id: str, data: dict):
    d_dir = ROOT / disease_id
    d_dir.mkdir(parents=True, exist_ok=True)
    data_dir = d_dir / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    # 1. config.py
    cfg_content = generate_config_py(disease_id, data)
    (d_dir / "config.py").write_text(cfg_content, encoding="utf-8")

    # 2. drugs.json
    drugs_payload = {
        "disease_id": disease_id,
        "disease_name": data["display_name"],
        "drugs": data["drugs"],
    }
    (data_dir / "drugs.json").write_text(json.dumps(drugs_payload, indent=2), encoding="utf-8")

    # 3. Clean relationships.json if needed
    rel_path = data_dir / "relationships.json"
    if rel_path.exists():
        try:
            rel_data = json.loads(rel_path.read_text(encoding="utf-8"))
            rels = rel_data.get("relationships", [])
            valid_types = {
                "TARGETS", "INVOLVED_IN", "BIOMARKER_FOR", "ASSOCIATED_WITH",
                "INTERACTS_WITH", "REGULATES", "UPREGULATES", "DOWNREGULATES",
                "HAS_PHENOTYPE", "EXPRESSED_IN", "EVALUATED_IN", "CONTRAINDICATED_IN"
            }
            cleaned_rels = []
            for r in rels:
                rt = r.get("type", "ASSOCIATED_WITH").upper().replace(" ", "_")
                if rt not in valid_types:
                    rt = "ASSOCIATED_WITH"
                r["type"] = rt
                if "description" not in r:
                    r["description"] = f"{r.get('source_id', '')} {rt} {r.get('target_id', '')}"
                cleaned_rels.append(r)
            rel_data["relationships"] = cleaned_rels
            rel_path.write_text(json.dumps(rel_data, indent=2), encoding="utf-8")
        except Exception as e:
            print(f"  Warning on relationships.json for {disease_id}: {e}")

    print(f"Successfully curated and updated {disease_id} -> {data['display_name']}")


def main():
    for did, data in DISEASES_DATA.items():
        update_disease(did, data)
        # Also mirror scleroderma to systemic_scleroderma if present
        if did == "scleroderma":
            update_disease("systemic_scleroderma", data)

    print("\nAll 12 disease modules curated to Tier-1 (L2) status!")

if __name__ == "__main__":
    main()
