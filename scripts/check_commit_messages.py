"""Validate commit subjects against the repository's Conventional Commits policy.

The release process (see RELEASING.md) derives version bumps and changelog
entries from commit messages, so commit subjects are part of the release
contract and not just a style preference.

Usage::

    python scripts/check_commit_messages.py                      # just the current commit
    python scripts/check_commit_messages.py --since-last-release # everything since the last tag
    python scripts/check_commit_messages.py --range v0.2.1..HEAD
    python scripts/check_commit_messages.py --since-last-release --advisory --github

Exit codes:
    0  every checked commit is valid (or --advisory was passed)
    1  at least one commit is invalid
    2  usage/git failure
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys

# Splitting a repo the size of this one must stay fast: one git invocation, no
# per-commit process spawn.
_RECORD_SEP = "\x1e"
_FIELD_SEP = "\x1f"
_LOG_FORMAT = _FIELD_SEP.join(("%H", "%an", "%ae", "%s", "%b")) + _RECORD_SEP

ALLOWED_TYPES = (
    "feat",
    "fix",
    "perf",
    "refactor",
    "revert",
    "build",
    "ci",
    "chore",
    "deps",
    "docs",
    "style",
    "test",
)

TYPE_MEANING = {
    "feat": "new user-visible functionality -> MINOR",
    "fix": "backward-compatible bug fix -> PATCH",
    "perf": "performance improvement -> PATCH",
    "refactor": "internal restructuring, no behavior change -> no release",
    "revert": "reverts an earlier commit -> match the reverted change",
    "build": "build tooling or packaging -> no release",
    "ci": "CI/CD configuration -> no release",
    "chore": "maintenance -> no release",
    "deps": "dependency bump -> no release unless it changes runtime behavior",
    "docs": "documentation only -> no release",
    "style": "formatting only -> no release",
    "test": "tests only -> no release",
}

# "<type>[(<scope>)][!]: <description>", e.g. "feat(compare): add N-way engine".
_HEADER_RE = re.compile(
    r"^(?P<type>[a-z][a-z0-9-]*)"
    r"(?:\((?P<scope>[^()\s]+)\))?"
    r"(?P<breaking>!)?"
    r": (?P<description>\S.*)$"
)
_BREAKING_FOOTER_RE = re.compile(r"^BREAKING[ -]CHANGE:\s*\S", re.MULTILINE)

# Subjects generated by git/GitHub/tooling that are not ours to police.
_EXEMPT_SUBJECT_RE = re.compile(
    r"^(?:"
    r"Merge (?:branch|remote-tracking branch|pull request|tag)\b"
    r"|Revert \""
    r"|(?:fixup|squash)! "
    r"|Initial commit$"
    r"|Auto-"
    r")"
)
_EXEMPT_AUTHOR_RE = re.compile(r"(\[bot\]|dependabot|github-actions)", re.IGNORECASE)

MAX_HEADER_LENGTH = 100


class Commit:
    """One commit from the range under validation."""

    def __init__(self, sha: str, author: str, email: str, subject: str, body: str) -> None:
        self.sha = sha
        self.author = author
        self.email = email
        self.subject = subject
        self.body = body

    @property
    def short_sha(self) -> str:
        return self.sha[:7]

    @property
    def is_exempt(self) -> bool:
        return bool(
            _EXEMPT_SUBJECT_RE.match(self.subject)
            or _EXEMPT_AUTHOR_RE.search(self.author)
            or _EXEMPT_AUTHOR_RE.search(self.email)
        )

    @property
    def is_breaking(self) -> bool:
        header = _HEADER_RE.match(self.subject)
        if header and header.group("breaking"):
            return True
        return bool(_BREAKING_FOOTER_RE.search(self.body))


def _run_git(args: list[str]) -> str:
    result = subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if result.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed:\n{result.stderr.strip()}")
    return result.stdout


def latest_release_tag() -> str | None:
    """Return the most recent release tag (``vX.Y.Z``) reachable from HEAD."""
    result = subprocess.run(
        ["git", "describe", "--tags", "--abbrev=0", "--match", "v[0-9]*"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if result.returncode != 0:
        return None
    tag = result.stdout.strip()
    return tag or None


def collect_commits(revision_range: str, limit: int | None = None) -> list[Commit]:
    args = ["log", f"--format={_LOG_FORMAT}"]
    if limit:
        args.append(f"--max-count={limit}")
    output = _run_git([*args, revision_range])
    commits: list[Commit] = []
    for record in output.split(_RECORD_SEP):
        record = record.strip("\n")
        if not record:
            continue
        fields = record.split(_FIELD_SEP)
        if len(fields) < 5:
            continue
        sha, author, email, subject, body = fields[:5]
        commits.append(Commit(sha, author, email, subject, body))
    return commits


def validate(commit: Commit) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) for one commit."""
    errors: list[str] = []
    warnings: list[str] = []

    header = _HEADER_RE.match(commit.subject)
    if not header:
        errors.append(
            'subject does not match "<type>[(<scope>)][!]: <summary>" '
            '(for example "fix(web): stop leaking paths in /api/ready")'
        )
        return errors, warnings

    commit_type = header.group("type")
    if commit_type not in ALLOWED_TYPES:
        errors.append(f"unknown type {commit_type!r}; use one of: {', '.join(ALLOWED_TYPES)}")

    if len(commit.subject) > MAX_HEADER_LENGTH:
        warnings.append(
            f"subject is {len(commit.subject)} characters (recommended maximum {MAX_HEADER_LENGTH})"
        )

    description = header.group("description")
    if description.endswith("."):
        warnings.append("summary ends with a period (Conventional Commits omits it)")

    if commit.is_breaking and commit_type in {"docs", "style", "test", "chore", "ci"}:
        warnings.append(
            f"'{commit_type}!' or a BREAKING CHANGE footer triggers a MINOR bump "
            "pre-1.0; use feat/fix for compatibility-affecting changes"
        )

    return errors, warnings


def _emit_github_warning(message: str) -> None:
    print(f"::warning::{message}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--range",
        dest="revision_range",
        default=None,
        help="git revision range to validate (default: the current commit)",
    )
    parser.add_argument(
        "--since-last-release",
        action="store_true",
        help="validate every commit since the most recent vX.Y.Z tag",
    )
    parser.add_argument(
        "--advisory",
        action="store_true",
        help="report violations but always exit 0 (used by advisory CI)",
    )
    parser.add_argument(
        "--github",
        action="store_true",
        help="also emit GitHub Actions ::warning:: annotations",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="emit a machine-readable JSON report instead of text",
    )
    args = parser.parse_args(argv)

    limit = None
    if args.since_last_release:
        tag = latest_release_tag()
        revision_range = f"{tag}..HEAD" if tag else "HEAD"
    elif args.revision_range:
        revision_range = args.revision_range
    else:
        # No explicit range: validate just the commit being created/reviewed.
        revision_range = "HEAD"
        limit = 1

    commits = collect_commits(revision_range, limit=limit)
    checked = [c for c in commits if not c.is_exempt]
    skipped = len(commits) - len(checked)

    report = {
        "range": revision_range,
        "checked": len(checked),
        "skipped": skipped,
        "violations": [],
        "warnings": [],
    }

    for commit in checked:
        errors, warnings = validate(commit)
        for message in errors:
            report["violations"].append(
                {"sha": commit.short_sha, "subject": commit.subject, "message": message}
            )
        for message in warnings:
            report["warnings"].append(
                {"sha": commit.short_sha, "subject": commit.subject, "message": message}
            )

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(f"Conventional Commits: checking {len(checked)} commit(s) in {revision_range}")
        if skipped:
            print(f"  ({skipped} merge/bot commit(s) skipped)")
        for violation in report["violations"]:
            print(f"  FAIL {violation['sha']}  {violation['subject']}")
            print(f"      {violation['message']}")
            if args.github:
                _emit_github_warning(
                    f"{violation['sha']}: {violation['message']} — subject: {violation['subject']}"
                )
        for warning in report["warnings"]:
            print(f"  WARN {warning['sha']}  {warning['subject']}")
            print(f"      {warning['message']}")
        if report["violations"]:
            print()
            print(
                "Commit convention: https://github.com/AdamEddahmouni/nosograph/blob/master/RELEASING.md"
            )
            print("Allowed types and release impact:")
            for commit_type in ALLOWED_TYPES:
                print(f"  {commit_type:<9} {TYPE_MEANING[commit_type]}")
        else:
            print("  OK: all checked commits follow Conventional Commits")

    if report["violations"] and not args.advisory:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
