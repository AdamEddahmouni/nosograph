"""Generated-versus-curated classification for disease modules.

The registry holds thousands of modules produced by ``med-research disease add``
alongside a small hand-curated core. Presenting them as equivalent would
overstate research coverage, so the distinction has to come from a deterministic
artifact marker rather than from a heuristic such as "few entities" or "short
description".

Two markers exist because they were introduced at different times:

``config_docstring``
    The ``disease add`` generator writes ``AUTO-GENERATED by
    ``med-research disease add``` into every generated ``config.py``. In the
    checked-in corpus sample this identifies 499 of 500 generated modules.

``profile_description``
    Older generator output prefixed ``profile.json`` descriptions with
    "auto-generated scaffold". Most generated modules carry real ontology prose
    instead, so this marker alone identifies only 39 of 500 — which is why both
    are checked.

A module that carries neither marker and is not one of the eight CI-validated
modules is reported as ``unknown``: the repository has no record of how it was
produced, and guessing would be worse than saying so.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable

from med_research.diseases.identifiers import CI_VALIDATED_DISEASES

GENERATOR_MARKER = "AUTO-GENERATED"
SCAFFOLD_MARKER = "auto-generated scaffold"

CURATION_STATES: tuple[str, ...] = ("generated", "curated", "unknown")


def generated_markers(module_root: Path, description: str = "") -> list[str]:
    """Return the generator markers found for one module.

    ``module_root`` is the disease module directory (the parent of ``data/``).
    Only the module's own text is inspected, so a sparse curated module is
    never mislabelled.
    """
    markers: list[str] = []
    if SCAFFOLD_MARKER in (description or "").lower():
        markers.append("profile_description")
    config_path = Path(module_root) / "config.py"
    try:
        if config_path.is_file():
            source = config_path.read_text(encoding="utf-8", errors="replace").upper()
            if GENERATOR_MARKER in source:
                markers.append("config_docstring")
    except OSError:
        pass
    return markers


def classify_curation_state(
    disease_id: str,
    module_root: Path,
    description: str = "",
) -> tuple[str, list[str]]:
    """Return ``(state, markers)`` for one module.

    ``state`` is one of :data:`CURATION_STATES`. Explicit generator markers win,
    then CI-validated membership, then ``unknown``.
    """
    markers = generated_markers(module_root, description)
    if markers:
        return "generated", markers
    if disease_id in CI_VALIDATED_DISEASES:
        return "curated", []
    return "unknown", []


def count_curation_states(states: Iterable[str]) -> dict[str, int]:
    """Count curation states into a fully populated, sorted mapping."""
    counts = {state: 0 for state in CURATION_STATES}
    for state in states:
        counts[state] = counts.get(state, 0) + 1
    return dict(sorted(counts.items()))


__all__ = [
    "CURATION_STATES",
    "GENERATOR_MARKER",
    "SCAFFOLD_MARKER",
    "classify_curation_state",
    "count_curation_states",
    "generated_markers",
]
